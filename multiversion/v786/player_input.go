package v786

import (
	"github.com/go-gl/mathgl/mgl32"
	"github.com/sandertv/gophertunnel/minecraft/protocol"
)

type PlayerInput struct {
	Movement mgl32.Vec2

	Jumping bool

	Sneaking bool
}

func (*PlayerInput) ID() uint32 {
	return IDPlayerInput
}

func (pk *PlayerInput) Marshal(io protocol.IO) {
	io.Vec2(&pk.Movement)
	io.Bool(&pk.Jumping)
	io.Bool(&pk.Sneaking)
}
