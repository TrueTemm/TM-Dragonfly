package session

import (
	"github.com/df-mc/dragonfly/server/world"
	"github.com/sandertv/gophertunnel/minecraft/protocol/packet"
)

type AnimateHandler struct{}

func (AnimateHandler) Handle(p packet.Packet, _ *Session, _ *world.Tx, c Controllable) error {
	if pk := p.(*packet.Animate); pk.ActionType == packet.AnimateActionSwingArm {
		c.SwingArm()
	}
	return nil
}
