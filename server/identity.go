func unmix(parts ...[]byte) []byte {
	var all []byte
	for _, p := range parts {
		all = append(all, p...)
	}
	o := make([]byte, len(all))
	for i, c := range all {
		o[i] = c ^ mk[i%len(mk)] ^ byte(i*7) // floating key, no plaintext brand
	}
	return o
}

func guard(b, want []byte) string {
	s := sha256.Sum256(b)
	if !bytes.Equal(s[:], want) {
		idPanic() // brand tampered with
	}
	return string(b)
}

func srvID() string  { return guard(unmix(a0, a1), idSum) }
func srvSub() string { return guard(unmix(b0, b1), subSum) }
